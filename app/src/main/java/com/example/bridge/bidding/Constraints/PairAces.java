package com.example.bridge.bidding.Constraints;

import com.example.bridge.bidding.Tools.Call;
import com.example.bridge.bidding.Tools.HandConstraint;
import com.example.bridge.bidding.Tools.HandSummary;
import com.example.bridge.bidding.Tools.IDescribeConstraint;
import com.example.bridge.bidding.Tools.PositionState;

import java.util.*;

/**
 * Constraint sprawdzający łączną liczbę asów posiadanych przez parę.
 * Różni się od klasy Aces tym, że bierze pod uwagę wiedzę o obu rękach partnerów.
 */
public class PairAces extends HandConstraint implements IDescribeConstraint {
    private final int[] count; // Dopuszczalne sumy asów w parze

    public PairAces(int... count) {
        this.count = count;
    }

    @Override
    public boolean conforms(Call call, PositionState ps, HandSummary hs) {
        Set<Integer> ourAces = hs.getCountAces();
        Set<Integer> partnerAces = ps.getPartner().getPublicHandSummary().getCountAces();

        if (ourAces == null || partnerAces == null) {
            return true; // Brak pełnej informacji - nie blokujemy licytacji
        }

        for (int mine : ourAces) {
            for (int partners : partnerAces) {
                int total = mine + partners;
                for (int c : count) {
                    if (total == c) return true;
                }
            }
        }
        return false;
    }

    @Override
    public String describe(Call call, PositionState ps) {
        if (count == null || count.length == 0) return "Aces: 0-4 (pair)";
        int min = Arrays.stream(count).min().orElse(0);
        int max = Arrays.stream(count).max().orElse(4);
        String val = (min == max) ? String.valueOf(min) : min + "-" + max;
        return "Aces: " + val + " (pair)";
    }
}




























































































































































































































































































































































































































































































